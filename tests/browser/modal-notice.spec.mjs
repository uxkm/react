import { test, expect } from '@playwright/test'

test.use({ timezoneId: 'Asia/Seoul' })

test('공지 모달은 일반 닫기 후 다시 열고, 하루 숨김은 새로고침 후에도 자정까지 유지한다', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-12T14:59:00.000Z') })
  await page.goto('/pub/guide/modal')
  const demo = page.locator('[data-notice-modal-demo]')
  const trigger = demo.getByRole('button', { name: '공지사항 모달 열기' })
  const modal = demo.getByRole('dialog')
  await trigger.click()
  await expect(modal).toBeVisible()
  await modal.locator('.modal_footer').getByRole('button', { name: '닫기', exact: true }).click()
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeEnabled()
  expect(await page.evaluate(() => localStorage.getItem('guide-notice-modal-v1'))).toBe(null)
  await trigger.click()
  await modal.getByRole('checkbox', { name: '오늘 하루 보지 않기' }).check()
  await modal.locator('.modal_close').click()
  await expect(trigger).toBeDisabled()
  expect(await page.evaluate(() => Number(localStorage.getItem('guide-notice-modal-v1')))).toBe(new Date('2026-11-12T15:00:00.000Z').getTime())
  await page.reload()
  await expect(trigger).toBeDisabled()
  await expect(modal).toHaveCount(0)
  await page.clock.fastForward(60050)
  await expect(trigger).toBeEnabled()
  await trigger.click()
  await expect(modal).toBeVisible()
})
