import { test, expect } from '@playwright/test'

test('B2B 헤더 로고와 전체메뉴의 키보드·아코디언·링크 동작', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/b2b')
  const header = page.locator('header.header')
  await expect(header.locator('.header_inner .logo img')).toHaveAttribute('src', '/images/common/logo_black.png')
  await expect(header.locator('.header_inner .logo img')).toHaveJSProperty('naturalWidth', 152)
  const trigger = header.getByRole('button', { name: '전체메뉴 열기' })
  await trigger.click()
  const menu = page.getByRole('dialog', { name: '전체메뉴', exact: true })
  await expect(menu).toBeVisible()
  await expect(menu.locator('.accordion.full-menu-content_accordion')).toHaveCount(1)
  await expect(menu.getByRole('link', { name: 'AI 서비스', exact: true })).toBeVisible()
  await expect(menu.getByRole('link', { name: '리더십 교육', exact: true })).toBeVisible()
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  await page.keyboard.press('Escape')
  await expect(menu).not.toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await menu.getByRole('button', { name: '회사소개', exact: true }).click()
  await expect(menu.getByRole('link', { name: 'AI 서비스', exact: true })).not.toBeVisible()
  await expect(menu.getByRole('link', { name: 'ESG Data', exact: true })).toBeVisible()
  await menu.getByRole('button', { name: '회사소개', exact: true }).click()
  await expect(menu.locator('.accordion_trigger[aria-expanded="true"]')).toHaveCount(0)
  await expect(menu.getByRole('link', { name: 'ESG Data', exact: true })).not.toBeVisible()
  await menu.getByRole('button', { name: '회사소개', exact: true }).click()
  await menu.getByRole('link', { name: '주가정보', exact: true }).click()
  await expect(page).toHaveURL(/\/b2b\/company\/investors\/stock-price$/)
  await expect(menu).not.toBeVisible()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await expect(page.locator('header.header .header_inner .logo')).toBeVisible()
  await page.getByRole('button', { name: '전체메뉴 열기' }).click()
  await menu.getByRole('button', { name: '회사소개', exact: true }).click()
  await menu.getByRole('link', { name: '재무정보', exact: true }).click()
  await expect(page).toHaveURL(/\/b2b\/company\/investors\/financial$/)
  await expect(page.getByRole('button', { name: '전체메뉴 열기' })).toBeVisible()
  expect(errors).toEqual([])
})

test('전체메뉴 프리뷰와 헤더 패널은 같은 메뉴를 표시한다', async ({ page }) => {
  await page.goto('/b2b/common/full-menu')
  await expect(page.locator('header.header, footer.footer, h1')).toHaveCount(0)
  await expect(page.locator('main').getByRole('link', { name: 'AI 서비스', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '회사소개', exact: true }).click()
  await expect(page.locator('main').getByRole('link', { name: 'ESG Data', exact: true })).toBeVisible()
  await expect(page.locator('header.header, footer.footer, h1')).toHaveCount(0)
  await page.goto('/b2b/common/gnb')
  await expect(page.locator('main header.header')).toHaveCount(1)
  const primaryNav = page.getByRole('navigation', { name: '주요 메뉴', exact: true })
  await expect(primaryNav).toBeVisible()
  await expect(primaryNav.getByRole('link')).toHaveCount(5)
  await expect(page.locator('header.header .header_company')).toBeVisible()
  await expect(page.locator('header.header .header_inquiry')).toBeVisible()
  await expect(page.locator('footer.footer, h1')).toHaveCount(0)
  await page.getByRole('button', { name: '전체메뉴 열기' }).click()
  await expect(page.getByRole('dialog', { name: '전체메뉴', exact: true })).toBeVisible()
  const dialog = page.getByRole('dialog', { name: '전체메뉴', exact: true })
  await dialog.getByRole('button', { name: '전체메뉴 닫기' }).click()
  await expect(dialog).not.toBeVisible()
})


test('스크롤 방향에 관계없이 B2B 헤더가 상단에 고정된다', async ({ page }) => {
  await page.goto('/b2b')
  await page.addStyleTag({ content: '.app-layout_main { min-height: 300vh; }' })
  const header = page.locator('header.header')
  if (page.viewportSize().width < 1440) {
    const scrollLeft = await page.evaluate(() => Math.min(200, document.documentElement.scrollWidth - document.documentElement.clientWidth))
    await page.evaluate((left) => window.scrollTo({ left, behavior: 'instant' }), scrollLeft)
    await expect.poll(() => page.evaluate(() => window.scrollX)).toBe(scrollLeft)
    expect(await header.evaluate((node) => node.scrollLeft)).toBe(0)
    await page.evaluate(() => window.scrollTo({ left: 0, behavior: 'instant' }))
  }
  for (const y of [400, 800, 600, 0]) {
    await page.evaluate((top) => window.scrollTo({ top, behavior: 'instant' }), y)
    await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(y)
    await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await expect(header).not.toHaveClass(/is-scroll-hidden/)
    await expect.poll(() => header.evaluate((node) => Math.round(node.getBoundingClientRect().top))).toBe(0)
    await expect.poll(() => page.locator('.app-layout').evaluate((node) => getComputedStyle(node).getPropertyValue('--app-header-height').trim())).toBe('68px')
  }
})
