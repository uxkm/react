import { test, expect } from '@playwright/test'

test('공통 푸터는 고객센터부터 표시하고 이미지·내부 링크가 정상 동작한다', async ({ page, isMobile }, testInfo) => {
  if (!isMobile) await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/b2b')
  const footer = page.getByRole('contentinfo', { name: '멀티캠퍼스 회사 정보' })
  await expect(footer).toHaveCount(1)
  await footer.scrollIntoViewIfNeeded()
  await expect(footer.getByRole('link', { name: '고객센터 1544-9001' })).toHaveAttribute('href', 'tel:15449001')
  await expect(footer.getByText('평일 08:00~20:00', { exact: true })).toBeVisible()
  await expect(footer.getByRole('link', { name: '개인정보처리방침', exact: true })).toBeVisible()
  const images = footer.locator('img')
  await expect(images).toHaveCount(9)
  await expect.poll(() => images.evaluateAll((nodes) => nodes.every((node) => node.complete && node.naturalWidth > 0))).toBe(true)
  expect(await footer.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true)
  await footer.screenshot({ path: testInfo.outputPath('footer.png') })
  await footer.getByRole('link', { name: '개인정보처리방침', exact: true }).click()
  await expect(page).toHaveURL(/\/b2b\/common\/privacy$/)
  await expect(page.getByRole('contentinfo', { name: '멀티캠퍼스 회사 정보' })).toHaveCount(1)
})

test('푸터 프리뷰는 중복 푸터가 없고 패밀리사이트는 GO를 눌러 새 창으로 이동한다', async ({ page, context }) => {
  await page.goto('/b2b/common/footer')
  await expect(page.locator('header.header')).toHaveCount(0)
  await expect(page.locator('h1')).toHaveCount(0)
  const footer = page.locator('footer.footer')
  await expect(footer).toHaveCount(1)
  const externalLinks = footer.locator('a[target="_blank"]')
  expect(await externalLinks.count()).toBeGreaterThan(0)
  for (const link of await externalLinks.all()) {
    await expect(link).toHaveAttribute('title', '새 창 열림')
    await expect(link).not.toContainText('(새 창)')
  }
  await expect(footer.locator('.footer_sr-only')).toHaveCount(0)
  const go = footer.getByRole('button', { name: '선택한 패밀리사이트로 이동' })
  await expect(go).toHaveAttribute('title', '새 창 열림')
  await expect(go).toBeDisabled()
  await context.route('https://www.opic.or.kr/**', (route) => route.fulfill({ body: '<title>OPIc</title>' }))
  const dropdown = footer.locator('.footer_family-dropdown')
  await dropdown.getByRole('button', { name: 'FAMILY SITE', exact: true }).click()
  await expect(dropdown.getByRole('menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dropdown.getByRole('menu')).not.toBeVisible()
  await dropdown.getByRole('button', { name: 'FAMILY SITE', exact: true }).click()
  await dropdown.getByRole('menuitemradio', { name: 'OPIc', exact: true }).click()
  await expect(dropdown.getByRole('menu')).not.toBeVisible()
  await expect(dropdown.getByRole('button', { name: 'OPIc', exact: true })).toBeVisible()
  await expect(go).toBeEnabled()
  const popupPromise = context.waitForEvent('page')
  await go.click()
  const popup = await popupPromise
  await expect(popup).toHaveURL('https://www.opic.or.kr/')
  await popup.close()
})

test('공통 Link의 새 창 링크는 title로 안내한다', async ({ page }) => {
  await page.goto('/pub/guide/link')
  const link = page.locator('a.link[target="_blank"]').first()
  await expect(link).toHaveAttribute('title', '새 창 열림')
  await expect(link).toHaveAttribute('rel', /noopener/)
})
