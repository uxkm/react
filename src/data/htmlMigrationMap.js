export function findHtmlPage(category, slug) {
  const section = htmlMigrationMap.find((item) => item.category === category)
  if (!section) return null

  const page = section.pages.find((item) => item.slug === slug)
  if (!page) return null

  return { section, page }
}

/**
 * 잘린 slug·오타 등으로 `findHtmlPage`가 실패할 때, 같은 section 안에서 slug 접두 일치가
 * 페이지 하나로만 좁혀지면 그 문서를 반환합니다.
 * (예: 검색/공유 URL이 `.../01-htmlStart/01-`처럼 잘리면 `01-html_start`로 복구)
 * 접두 일치가 0개 또는 2개 이상이면 null.
 */
export function findUniqueHtmlPageBySlugPrefix(category, slugPrefix) {
  if (slugPrefix == null) return null
  const normalized = String(slugPrefix).trim()
  if (normalized.length < 2) return null

  const section = htmlMigrationMap.find((item) => item.category === category)
  if (!section) return null

  const candidates = section.pages.filter((p) => p.slug.startsWith(normalized))
  if (candidates.length !== 1) return null

  return { section, page: candidates[0] }
}
